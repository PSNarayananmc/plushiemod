#!/usr/bin/env python3
"""Generates PlushieGeometry.java from the Bedrock geometry JSON.

Conversion (Bedrock -> Java model space):
  - y is flipped: java_y_top = 24 - bedrock_y, ground plane at java y=24
  - cube box: java addBox(ox, 24 - oy - sy, oz, sx, sy, sz)
  - part pivots: (px, 24 - py, pz)
  - part rotations: (-rx, -ry, +rz) in radians (Bedrock ZYX, y-up <-> Java ZYX, y-down)
  - per-face UV kept exactly as authored (negative uv_size = mirrored face)
"""
import json

SRC = '/home/z/my-project/addon_extracted/plushie_party_rp/models/entity/creeper_plushie.geo.json'
OUT = '/home/z/my-project/src/main/java/com/redeagle/plushieparty/client/model/PlushieGeometry.java'

geo = json.load(open(SRC))
target = [g for g in geo['minecraft:geometry']
          if g['description']['identifier'].endswith('.creeper_plushie')][0]

FACE_ORDER = ['north', 'east', 'south', 'west', 'up', 'down']

def emit():
    body_cubes = []
    leg_parts = []
    for bone in target['bones']:
        if bone['name'] != 'body':
            continue
        for c in bone.get('cubes', []):
            ox, oy, oz = c['origin']
            sx, sy, sz = c['size']
            has_rot = bool(c.get('rotation'))
            # java space box
            min_x, max_x = ox, ox + sx
            min_z, max_z = oz, oz + sz
            min_y, max_y = 24 - (oy + sy), 24 - oy
            faces = {}
            uv = c.get('uv', {})
            if isinstance(uv, dict):
                for f in FACE_ORDER:
                    if f in uv:
                        u, v = uv[f]['uv']
                        w, h = uv[f]['uv_size']
                        tw, th = 32, 32
                        faces[f] = (u / tw, v / th, (u + w) / tw, (v + h) / th)
            if has_rot:
                px, py, pz = c['pivot']
                rx, ry, rz = c['rotation']
                local_min_y = py - oy - sy
                local = (min_x - px, local_min_y, min_z - pz,
                         max_x - px, local_min_y + sy, max_z - pz)
                leg_parts.append(dict(pivot=(px, 24 - py, pz), rot=(-rx, -ry, rz), box=local, faces=faces))
            else:
                body_cubes.append(dict(box=(min_x, min_y, min_z, max_x, max_y, max_z), faces=faces))
    return body_cubes, leg_parts

def face_expr(faces, name):
    f = faces.get(name)
    if not f:
        return 'null'
    return f'new FaceUV({f[0]:.6f}F, {f[1]:.6f}F, {f[2]:.6f}F, {f[3]:.6f}F)'

def cube_ctor(box, faces):
    mn = ', '.join(f'{v:.6f}F' for v in box[:3])
    mx = ', '.join(f'{v:.6f}F' for v in box[3:])
    fl = ', '.join(face_expr(faces, n) for n in FACE_ORDER)
    return f'new Cube({mn}, {mx}, {fl})'

body_cubes, leg_parts = emit()

java = []
java.append('package com.redeagle.plushieparty.client.model;')
java.append('')
java.append('import java.util.List;')
java.append('')
java.append('/**')
java.append(' * Creeper Plushie model, converted 1:1 from the Bedrock geometry')
java.append(' * {@code geometry.re_plushie_party.creeper_plushie} (format 1.12.0).')
java.append(' *')
java.append(' * <p>Bedrock coordinates were converted to Java model space: y is flipped')
java.append(' * (ground plane at y = 24), and bone rotations follow the standard')
java.append(' * (-x, -y, z) Bedrock-to-Java conversion. Per-face UVs (including mirrored')
java.append(' * faces authored with negative UV sizes) are preserved exactly.</p>')
java.append(' *')
java.append(' * <p>Generated by scripts/generate_model.py - do not hand-edit.</p>')
java.append(' */')
java.append('public final class PlushieGeometry {')
java.append('    public static final int TEXTURE_WIDTH = 32;')
java.append('    public static final int TEXTURE_HEIGHT = 32;')
java.append('    /** Java model units are 1/16 of a block; the ground plane sits at this y. */')
java.append('    public static final float GROUND_Y = 24.0F;')
java.append('')
java.append('    /** Per-face UV rect in 0..1 texture space. u1/v1 may be smaller than u0/v0 for mirrored faces. */')
java.append('    public record FaceUV(float u0, float v0, float u1, float v1) {}')
java.append('')
java.append('    /** Axis-aligned box in Java model units with up to six textured faces. */')
java.append('    public record Cube(float minX, float minY, float minZ, float maxX, float maxY, float maxZ,')
java.append('                       FaceUV north, FaceUV east, FaceUV south, FaceUV west, FaceUV up, FaceUV down) {}')
java.append('')
java.append('    /** A transformable model part (pivot + rotation in radians) carrying cubes. */')
java.append('    public record Part(String name, float px, float py, float pz,')
java.append('                       float rx, float ry, float rz, List<Cube> cubes) {}')
java.append('')

java.append('    /** Cubes directly attached to the "body" bone (unrotated). */')
java.append('    public static final List<Cube> BODY_CUBES = List.of(')
java.append(',\n'.join('            ' + cube_ctor(c['box'], c['faces']) for c in body_cubes))
java.append('    );')
java.append('')
java.append('    /** The four splayed leg parts (bedrock rotations -70/-70/70/70 on x, -15/15 on y). */')
java.append('    public static final List<Part> LEG_PARTS = List.of(')
leg_lines = []
for i, p in enumerate(leg_parts):
    pv = ', '.join(f'{v:.6f}F' for v in p['pivot'])
    rv = ', '.join(f'{v:.6f}F' for v in p['rot'])
    leg_lines.append(
            f'            new Part("leg{i}", {pv}, {rv}, List.of(\n'
            '                    ' + cube_ctor(p['box'], p['faces']) + '))')
java.append(',\n'.join(leg_lines))
java.append('    );')
java.append('')
java.append('    private PlushieGeometry() {')
java.append('    }')
java.append('}')

open(OUT, 'w').write('\n'.join(java) + '\n')
print('wrote', OUT, len(body_cubes), 'body cubes,', len(leg_parts), 'leg parts')
